#!/usr/bin/env python3
"""Genera el módulo Sass del Post III desde su snapshot DTCG versionado."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from dtcg_format import DTCGError, color_hex, metadata, validate_document  # noqa: E402

DEFAULT_TOKENS = ROOT / "assets/data/tesis-post3/visual_identity_tokens_v1.json"
DEFAULT_OUTPUT = ROOT / "_sass/_post3-data-viz-tokens.scss"
DEFAULT_MANIFEST = ROOT / "assets/images/tesis-post3/manifest.json"
DEFAULT_CSS = ROOT / "assets/css/main.scss"
COLOR_NAMES = (
    "canvas",
    "surface",
    "ink",
    "muted",
    "grid",
    "accent",
    "focus",
    "positive",
    "negative",
    "warning",
)
SERIES_NAMES = ("one", "two", "three", "four", "five", "six")
SIZE_NAMES = ("caption", "label", "body", "title")
SPACE_NAMES = ("xs", "sm", "md", "lg", "xl")


class TokenError(ValueError):
    """El snapshot no satisface el contrato visual local."""


def _value(node: dict[str, Any]) -> Any:
    if "$value" not in node:
        raise TokenError("token sin $value")
    return node["$value"]


def _color(tokens: dict[str, Any], mode: str, name: str) -> str:
    try:
        return color_hex(tokens["color"][mode][name], f"color.{mode}.{name}")
    except (KeyError, TypeError) as error:
        raise TokenError(f"falta color {mode}.{name}") from error


def _dimension(tokens: dict[str, Any], group: str, name: str) -> str:
    try:
        item = _value(tokens[group][name])
        number = item["value"]
        unit = item["unit"]
    except (KeyError, TypeError) as error:
        raise TokenError(f"falta dimensión {group}.{name}") from error
    if not isinstance(number, (int, float)) or isinstance(number, bool) or unit not in {"px", "rem"}:
        raise TokenError(f"dimensión inválida {group}.{name}: {item!r}")
    return f"{number:g}{unit}"


def _font_family(tokens: dict[str, Any]) -> str:
    try:
        family = _value(tokens["font"]["family"]["data"])
    except (KeyError, TypeError) as error:
        raise TokenError("falta font.family.data") from error
    if not isinstance(family, list) or not family or not all(isinstance(item, str) and item for item in family):
        raise TokenError("font.family.data debe ser una lista no vacía")
    return ", ".join(f'"{item}"' if " " in item else item for item in family)


def validate_tokens(tokens: dict[str, Any]) -> None:
    validate_document(tokens)
    metadata(tokens)
    _font_family(tokens)
    for name in SIZE_NAMES:
        _dimension(tokens["font"], "size", name)
    for name in SPACE_NAMES:
        _dimension(tokens, "space", name)
    _dimension(tokens, "radius", "panel")
    for mode in ("light", "dark"):
        for name in COLOR_NAMES:
            _color(tokens, mode, name)
        try:
            series = tokens["color"][mode]["series"]
        except (KeyError, TypeError) as error:
            raise TokenError(f"falta color {mode}.series") from error
        for name in SERIES_NAMES:
            color_hex(series[name], f"color.{mode}.series.{name}")


def _theme_lines(tokens: dict[str, Any], mode: str) -> list[str]:
    lines = [f"  /* {mode} */"]
    lines.extend(f"  --c3-viz-{name}: {_color(tokens, mode, name)};" for name in COLOR_NAMES)
    series = tokens["color"][mode]["series"]
    lines.extend(
        f"  --c3-viz-series-{name}: {color_hex(series[name], f'color.{mode}.series.{name}')};"
        for name in SERIES_NAMES
    )
    return lines


def render(tokens: dict[str, Any], source_sha256: str) -> str:
    validate_tokens(tokens)
    light = _theme_lines(tokens, "light")
    light.append(f"  --c3-viz-font-family: {_font_family(tokens)};")
    light.extend(
        f"  --c3-viz-font-{name}: {_dimension(tokens['font'], 'size', name)};"
        for name in SIZE_NAMES
    )
    light.extend(
        f"  --c3-viz-space-{name}: {_dimension(tokens, 'space', name)};"
        for name in SPACE_NAMES
    )
    light.append(f"  --c3-viz-radius-panel: {_dimension(tokens, 'radius', 'panel')};")
    dark = _theme_lines(tokens, "dark")
    return "\n".join(
        [
            "/* Generated by scripts/build_post3_visual_tokens.py; edit the DTCG snapshot instead.",
            f"   Source SHA-256: {source_sha256} */",
            "@mixin light-theme {",
            *light,
            "}",
            "",
            "@mixin dark-theme {",
            *dark,
            "}",
            "",
        ]
    )


def validate_css_binding(css: str) -> None:
    start = css.find("/* Adaptador del contrato 3cucharadas-visualizacion-datos.")
    end = css.find(".page__content table {", start)
    if start < 0 or end < 0:
        raise TokenError("CSS Post III sin bloque adaptador")
    block = css[start:end]
    before_print = block.split("@media print", 1)[0]
    required = (
        '@use "post3-data-viz-tokens" as post3-viz;',
        '@include post3-viz.light-theme;',
        '@include post3-viz.dark-theme;',
        'color: var(--c3-viz-ink);',
        'background: var(--c3-viz-surface);',
        'font-family: var(--c3-viz-font-family);',
        '--focus-ring: var(--c3-viz-focus);',
    )
    for anchor in required:
        source = css if anchor.startswith("@use") else before_print
        if source.count(anchor) != 1:
            raise TokenError(f"CSS Post III desacoplado de tokens: {anchor}")
    if any(line.lstrip().startswith("--c3-viz-") for line in before_print.splitlines()):
        raise TokenError("CSS Post III sobrescribe tokens fuera de impresión")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tokens", type=Path, default=DEFAULT_TOKENS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--css-source", type=Path, default=DEFAULT_CSS)
    parser.add_argument("--check", action="store_true", help="Falla si el Sass derivado está obsoleto")
    args = parser.parse_args()
    try:
        source = args.tokens.read_bytes()
        tokens = json.loads(source)
        if not isinstance(tokens, dict):
            raise TokenError("la raíz del snapshot debe ser un objeto")
        source_sha256 = hashlib.sha256(source).hexdigest()
        expected = render(tokens, source_sha256)
        validate_css_binding(args.css_source.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, TokenError, DTCGError) as error:
        print(f"POST3_VISUAL_TOKENS_INVALID: {error}", file=sys.stderr)
        return 2
    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except OSError as error:
            print(f"POST3_VISUAL_TOKENS_STALE: {error}", file=sys.stderr)
            return 1
        if current != expected:
            print(f"POST3_VISUAL_TOKENS_STALE: {args.output}", file=sys.stderr)
            return 1
        try:
            manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
            manifest_sha256 = manifest["visual_identity"]["sha256"]
        except (OSError, json.JSONDecodeError, KeyError, TypeError) as error:
            print(f"POST3_VISUAL_TOKENS_MANIFEST_INVALID: {error}", file=sys.stderr)
            return 2
        if manifest_sha256 != source_sha256:
            print(
                "POST3_VISUAL_TOKENS_MANIFEST_STALE: "
                f"{args.manifest} declara {manifest_sha256!r}, se esperaba {source_sha256}",
                file=sys.stderr,
            )
            return 1
        print("POST3_VISUAL_TOKENS_CURRENT")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8")
    print(f"POST3_VISUAL_TOKENS_WRITTEN: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
